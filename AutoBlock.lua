                                    KillersFolder:GetChildren()
                                ) do
                                    local HRP =
                                        Killer:FindFirstChild(
                                            "HumanoidRootPart"
                                        )

                                    if HRP then
                                        local Distance =
                                            (
                                                Root.Position
                                                - HRP.Position
                                            ).Magnitude

                                        if Distance < ClosestDistance then
                                            ClosestDistance = Distance
                                            ClosestHRP = HRP
                                        end
                                    end
                                end

                                if ClosestHRP then
                                    Looking = true

                                    local OldAutoRotate =
                                        Humanoid.AutoRotate

