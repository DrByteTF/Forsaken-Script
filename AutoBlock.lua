--==============================================================
-- RANGE VISUAL FUNCTIONS
--==============================================================

local function RemoveRangeVisual(Model)
    local Visual = RangeVisuals[Model]

    if Visual then
        if Visual.Folder then
            Visual.Folder:Destroy()
        end

        RangeVisuals[Model] = nil
    end
end

local function CreateRangeVisual(Model)
    if RangeVisuals[Model] then
        return RangeVisuals[Model]
    end

    local Folder = Instance.new("Folder")
    Folder.Name = "M4prRangeVisual"
    Folder.Parent = workspace

    local Visual = {
        Folder = Folder,
        Parts = {},
        Mode = nil,
    }

    RangeVisuals[Model] = Visual

    return Visual
end

local function MakePart(Folder)
    local Part = Instance.new("Part")

    Part.Anchored = true
    Part.CanCollide = false
    Part.CanTouch = false
    Part.CanQuery = false
    Part.CastShadow = false

    Part.Material = Enum.Material.SmoothPlastic
    Part.Transparency = 0.78

    Part.Parent = Folder

    return Part
end

local function ClearParts(Visual)
    for _, Part in ipairs(Visual.Parts) do
        if Part then
            Part:Destroy()
        end
    end

    table.clear(Visual.Parts)
end

local function UpdateRangeVisual(Model, HRP)
    if not RangeVisual or not HRP then
        RemoveRangeVisual(Model)
        return
    end

    local Character = LocalPlayer.Character
    local PlayerHRP = Character
        and Character:FindFirstChild("HumanoidRootPart")

    if not PlayerHRP then
        return
    end

    local Visual = CreateRangeVisual(Model)

    local Origin = HRP.Position
    local Range = GuestRange

    local Offset = PlayerHRP.Position - Origin

    local FlatOffset = Vector3.new(
        Offset.X,
        0,
        Offset.Z
    )

    local Distance = FlatOffset.Magnitude

    local InRange = Distance <= Range
    local InFacing = true

    if GuestFace and InRange and Distance > 0.001 then
        local Direction = FlatOffset.Unit

        local Look = HRP.CFrame.LookVector

        local FlatLook = Vector3.new(
            Look.X,
            0,
            Look.Z
        )

        if FlatLook.Magnitude > 0.001 then
            FlatLook = FlatLook.Unit

            local Dot = FlatLook:Dot(Direction)

            InFacing = Dot > GuestDot
        end
    end

    local IsValid = InRange and InFacing
    local ZoneColor = IsValid and GREEN or RED

    --==========================================================
    -- NORMAL RANGE CIRCLE
    --==========================================================

    if not GuestFace then
        if Visual.Mode ~= "Circle" then
            ClearParts(Visual)

            local Circle = MakePart(Visual.Folder)

            Circle.Shape = Enum.PartType.Cylinder

            table.insert(Visual.Parts, Circle)

            Visual.Circle = Circle
            Visual.Mode = "Circle"
        end

        local Circle = Visual.Circle

        Circle.Color = ZoneColor

        Circle.Size = Vector3.new(
            0.12,
            Range * 2,
            Range * 2
        )

        Circle.CFrame =
            CFrame.new(
                Origin + Vector3.new(0, 0.04, 0)
            )
            * CFrame.Angles(0, 0, math.rad(90))

        return
    end

    --==========================================================
    -- FACING FAN
    --==========================================================

    if Visual.Mode ~= "Fan" then
        ClearParts(Visual)
        Visual.Mode = "Fan"
    end

    local SegmentCount = 40

    local HalfAngle = math.acos(
        math.clamp(GuestDot, -1, 1)
    )

    local Forward = HRP.CFrame.LookVector

    local FlatForward = Vector3.new(
        Forward.X,
        0,
        Forward.Z
    )

    if FlatForward.Magnitude <= 0.001 then
        return
    end

    FlatForward = FlatForward.Unit

    local Right = Vector3.new(
        -FlatForward.Z,
        0,
        FlatForward.X
    )

    while #Visual.Parts < SegmentCount do
        local Part = MakePart(Visual.Folder)
        table.insert(Visual.Parts, Part)
    end

    while #Visual.Parts > SegmentCount do
        local Part = table.remove(Visual.Parts)
        Part:Destroy()
    end

    for i = 1, SegmentCount do
        local Part = Visual.Parts[i]

        local T = (i - 0.5) / SegmentCount

        local Angle =
            -HalfAngle
            + (HalfAngle * 2 * T)

        local Direction =
            FlatForward * math.cos(Angle)
            + Right * math.sin(Angle)

        Direction = Direction.Unit

        local AngularStep =
            (HalfAngle * 2) / SegmentCount

        local Width =
            math.max(
                0.08,
                Range * math.tan(AngularStep)
            )

        local Center =
            Origin
            + Direction * (Range / 2)
            + Vector3.new(0, 0.04, 0)

        Part.Color = ZoneColor

        Part.Size = Vector3.new(
            Width,
            0.12,
            Range
        )

        Part.CFrame = CFrame.lookAt(
            Center,
            Center + Direction,
            Vector3.new(0, 1, 0)
        )
    end
end

