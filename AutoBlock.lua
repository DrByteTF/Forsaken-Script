                                --==================================================

                                if BlockType == "Sound" then
                                    for _, Obj in ipairs(
                                        Model:GetDescendants()
                                    ) do
                                        if Obj:IsA("Sound")
                                            and ValidSounds[Obj.SoundId] then

                                            local InRange =
                                                (
                                                    HumanoidRootPart.Position
                                                    - HRP.Position
                                                ).Magnitude
                                                <= GuestRange

                                            if Obj.IsPlaying then
                                                local CanBlock = InRange

                                                if GuestFace and CanBlock then
                                                    local Offset =
                                                        HumanoidRootPart.Position
                                                        - HRP.Position

