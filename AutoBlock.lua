                                -- ANIMATION MODE
                                --==================================================

                                elseif BlockType == "Animation" then
                                    local Humanoid =
                                        Model:FindFirstChildOfClass(
                                            "Humanoid"
                                        )

                                    local Animator =
                                        Humanoid
                                        and Humanoid:FindFirstChildOfClass(
                                            "Animator"
                                        )

                                    if Animator then
                                        for _, Track in ipairs(
                                            Animator:GetPlayingAnimationTracks()
                                        ) do
                                            local Animation =
                                                Track.Animation

                                            local AnimationId =
                                                Animation
                                                and Animation.AnimationId

                                            if AnimationId
                                                and ValidAnimations[AnimationId] then

                                                local InRange =
                                                    (
                                                        HumanoidRootPart.Position
                                                        - HRP.Position
                                                    ).Magnitude
                                                    <= GuestRange

                                                local CanBlock = InRange

                                                if GuestFace and CanBlock then
                                                    local Offset =
                                                        HumanoidRootPart.Position
                                                        - HRP.Position

                                                    if Offset.Magnitude > 0.001 then
                                                        local Direction =
                                                            Offset.Unit

                                                        local Dot =
                                                            HRP.CFrame.LookVector
                                                            :Dot(Direction)

                                                        CanBlock =
                                                            Dot > GuestDot
                                                    end
                                                end

                                                if PlayedOutside[Track] == nil then
                                                    PlayedOutside[Track] =
                                                        not CanBlock
                                                end

                                                if CanBlock
                                                    and not PlayedOutside[Track]
                                                    and not Blocked[Track] then

                                                    Blocked[Track] = true

                                                    RemoteEvent:FireServer(
                                                        "UseActorAbility",
                                                        {"Block"}
                                                    )
                                                end
                                            end
                                        end
                                    end
                                end
                            end
                        end
                    end

                    -- Clean up finished animations
                    for Track in pairs(PlayedOutside) do
                        if typeof(Track) == "Instance"
                            and Track:IsA("AnimationTrack")
                            and not Track.IsPlaying then

                            PlayedOutside[Track] = nil
                            Blocked[Track] = nil
                        end
                    end
                end

                task.wait(0.1)
            end
        end)
    end
