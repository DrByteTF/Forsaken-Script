                                                    and not PlayedOutside[Obj]
                                                    and not Blocked[Obj] then

                                                    Blocked[Obj] = true

                                                    RemoteEvent:FireServer(
                                                        "UseActorAbility",
                                                        {"Block"}
                                                    )
                                                end
                                            else
                                                PlayedOutside[Obj] = nil
                                                Blocked[Obj] = nil
                                            end
                                        end
                                    end

