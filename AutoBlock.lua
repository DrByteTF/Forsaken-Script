                                    local EndTime = tick() + 0.5

                                    while tick() < EndTime and AnimLook do
                                        local KillerModel =
                                            ClosestHRP.Parent

                                        local KillerHumanoid =
                                            KillerModel
                                            and KillerModel:
                                                FindFirstChildOfClass(
                                                    "Humanoid"
                                                )

                                        if KillerHumanoid then
                                            local TargetPos =
                                                ClosestHRP.Position
